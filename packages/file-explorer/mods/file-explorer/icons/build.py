#!/usr/bin/env python3
"""Rebuilds this folder from a release of Material Icon Theme (MIT).

    npm pack material-icon-theme@<version> && tar -xzf material-icon-theme-<version>.tgz
    python3 mods/file-explorer/icons/build.py package

Copies the theme's SVGs and its LICENSE here and writes map.js: which icon a file
name, a file extension and a folder name get. An open folder's icon is its closed
one with "-open".
"""
import json, os, shutil, sys

package = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
manifest = json.load(open(os.path.join(package, "dist", "material-icons.json")))
version = json.load(open(os.path.join(package, "package.json")))["version"]

# An icon's name in the manifest -> its file, without ".svg".
files = {name: os.path.splitext(os.path.basename(d["iconPath"]))[0] for name, d in manifest["iconDefinitions"].items()}

for old in os.listdir(here):
    if old.endswith(".svg"):
        os.remove(os.path.join(here, old))
for name in sorted(set(files.values())):
    shutil.copyfile(os.path.join(package, "icons", name + ".svg"), os.path.join(here, name + ".svg"))
shutil.copyfile(os.path.join(package, "LICENSE"), os.path.join(here, "LICENSE"))

def table(source, key):
    return {k.lower(): files[v] for k, v in sorted(source.get(key, {}).items())}

# A closed folder icon -> its open one, where that isn't the same name with "-open".
opened = {}

def tables(source):
    for name, icon in source.get("folderNames", {}).items():
        closed, expanded = files[icon], files[source["folderNamesExpanded"][name]]
        if expanded != closed + "-open":
            assert opened.setdefault(closed, expanded) == expanded, name
    return {"names": table(source, "fileNames"), "exts": table(source, "fileExtensions"), "folders": table(source, "folderNames")}

def js(value):
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)

dark, light = tables(manifest), tables(manifest["light"])
out = [
    f"// Generated by build.py from material-icon-theme {version} (MIT, see LICENSE). Do not edit.",
    f"export const VERSION = {js(version)};",
    f"export const FILE = {js(files[manifest['file']])};",
    f"export const FOLDER = {js(files[manifest['folder']])};",
    "// Keys are lower case. A name or a folder with a slash is matched with its parent folder.",
]
for name, value in dark.items():
    out.append(f"export const {name.upper()} = {js(value)};")
out.append(f"// What differs on a light theme.\nexport const LIGHT = {js(light)};")
out.append(f'// Open folder icons that are not the closed one with "-open".\nexport const OPEN = {js(dict(sorted(opened.items())))};')
open(os.path.join(here, "map.js"), "w").write("\n".join(out) + "\n")
print(f"{len(set(files.values()))} icons, material-icon-theme {version}")
